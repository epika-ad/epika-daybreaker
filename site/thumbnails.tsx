// Gallery thumbnails: one small monochrome sketch per component, drawn from a
// few shapes in a single ink colour. They are pictures, not live components.

// A shape is [kind, ...numbers]. Rectangles: x, y, width, height, radius.
// Circles: centre x, centre y, radius. Paths take the path data instead.
type Shape =
  | [kind: "s" | "m" | "l" | "o" | "d" | "k", ...box: number[]]
  | [kind: "cs" | "cm" | "cl" | "co" | "ck", ...circle: number[]]
  | [kind: "line" | "fill" | "bold" | "cut", d: string];

// how strongly each kind is inked: solid, mid, light
const ink = { s: 0.85, m: 0.3, l: 0.1 } as const;

const draw = (shape: Shape, key: number) => {
  const [kind, ...rest] = shape;
  if (kind === "line" || kind === "bold" || kind === "fill" || kind === "cut") {
    const d = rest[0] as string;
    return kind === "fill" ? (
      <path key={key} d={d} fill="currentColor" fillOpacity={ink.m} />
    ) : (
      <path
        key={key}
        d={d}
        fill="none"
        // "cut" draws in the background colour, over a solid shape
        stroke={kind === "cut" ? "var(--wz-background)" : "currentColor"}
        strokeOpacity={kind === "line" ? 0.45 : kind === "bold" ? ink.s : 1}
        strokeWidth={kind === "bold" ? 3 : kind === "cut" ? 2 : 1.5}
        strokeLinecap="round"
        strokeLinejoin="round"
      />
    );
  }
  const n = rest as number[];
  const tone = kind.at(-1) as "s" | "m" | "l" | "o" | "d" | "k";
  // "k" knocks a shape out of a solid one; "o" and "d" are outlines
  const paint =
    tone === "k"
      ? { fill: "var(--wz-background)" }
      : tone === "o" || tone === "d"
        ? {
            fill: "none",
            stroke: "currentColor",
            strokeOpacity: 0.4,
            strokeWidth: 1.5,
            strokeDasharray: tone === "d" ? "4 3" : undefined,
          }
        : { fill: "currentColor", fillOpacity: ink[tone] };
  return kind.length === 2 ? (
    <circle key={key} cx={n[0]} cy={n[1]} r={n[2]} {...paint} />
  ) : (
    <rect
      key={key}
      x={n[0]}
      y={n[1]}
      width={n[2]}
      height={n[3]}
      rx={n[4] ?? Math.min(n[2] ?? 0, n[3] ?? 0) / 2}
      {...paint}
    />
  );
};

const chevron = (x: number, y: number): Shape => ["line", `M${x} ${y}l4 4 4-4`];
// evenly spaced dots, for calendar grids
const dots = (x: number, y: number, columns: number, rows: number): Shape[] =>
  Array.from(
    { length: columns * rows },
    (_, index): Shape => [
      "cm",
      x + (index % columns) * 11,
      y + Math.floor(index / columns) * 10,
      2,
    ],
  );
const bars = (heights: number[], tone: "s" | "m" = "s"): Shape[] =>
  heights.map(
    (height, index): Shape => [
      tone,
      34 + index * 20,
      80 - height,
      12,
      height,
      3,
    ],
  );

